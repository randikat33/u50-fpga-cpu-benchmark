#!/usr/bin/env python3
"""Generate common/hq_log_tables.h: tables of the fixed-point natural logarithm used by the QE scheme.
  LN_T[i] = round(2^32 * ln(1 + i/1024))          (Q32, i = 0..1023)
  LN_R[i] = round(2^31 / (1 + i/1024))            (Q31, i = 0..1023)
  LN2_Q40 = round(2^40 * ln 2)
Computed with 60-digit decimal arithmetic, so the rounding of every entry is exact."""
from decimal import Decimal, getcontext, ROUND_HALF_EVEN
import os
getcontext().prec = 60
N = 1024
def rnd(x): return int(x.to_integral_value(rounding=ROUND_HALF_EVEN))
T = [rnd(Decimal(2) ** 32 * (1 + Decimal(i) / N).ln()) for i in range(N)]
R = [rnd(Decimal(2) ** 31 / (1 + Decimal(i) / N)) for i in range(N)]
LN2 = rnd(Decimal(2) ** 40 * Decimal(2).ln())
assert max(T) < 2**32 and max(R) <= 2**31
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "common", "hq_log_tables.h")
with open(out, "w") as f:
    f.write("// hq_log_tables.h - GENERATED by scripts/gen_log_tables.py. Do not edit.\n#pragma once\n#include <cstdint>\n\n")
    f.write(f"#define HQ_LN2_Q40 {LN2}ll\n")
    for name, tab in (("HQ_LN_T_INIT", T), ("HQ_LN_R_INIT", R)):
        f.write(f"#define {name} {{ \\\n")
        for k in range(0, N, 8):
            f.write("  " + ",".join(f"{v}u" for v in tab[k:k + 8]) + ("," if k + 8 < N else "") + " \\\n")
        f.write("}\n")
print("wrote", out)
